// Package gen 把 proto 消息生成 GORM 实体。
//
// 只生成三样东西：结构体（含 gorm tag）、TableName()、ToPB / FromXxx。
// CRUD、hook、关联装配一律不生成——那些由业务代码自己写。
package gen

import (
	"path"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

// Options 控制生成行为。
type Options struct {
	// Package 是生成文件的 Go 包名；为空时沿用输入 proto 的 go_package 名。
	Package string
	// Suffix 是生成文件名后缀，默认 .sgorm.go。
	Suffix string
}

const generatedFileImportPath = protogen.GoImportPath("protoc-gen-sgorm/target")

// Generate 为每个待生成文件输出一个 <proto 基名>.sgorm.go。
// 文件里没有 ormable 消息时不产生任何输出。
func Generate(plugin *protogen.Plugin, opts Options) error {
	if opts.Suffix == "" {
		opts.Suffix = ".sgorm.go"
	}
	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}
		models, err := buildModels(file)
		if err != nil {
			return err
		}
		if len(models) == 0 {
			continue
		}
		pkg := opts.Package
		if pkg == "" {
			pkg = string(file.GoPackageName)
		}
		name := path.Base(file.GeneratedFilenamePrefix) + opts.Suffix
		// 传一个与输入文件不同的 import path：否则 protogen 认为目标文件与 native 同包，
		// 会把 native.Transaction 渲染成裸 Transaction。
		g := plugin.NewGeneratedFile(name, generatedFileImportPath)
		emitHeader(g, file)
		g.P("package ", pkg)
		for _, m := range models {
			emitModel(g, m)
		}
	}
	return nil
}

// emitHeader 写文件头。protogen 不会自动加注释头，由插件自己负责。
func emitHeader(g *protogen.GeneratedFile, file *protogen.File) {
	g.P("// Code generated by protoc-gen-sgorm. DO NOT EDIT.")
	g.P("// source: ", file.Desc.Path())
	g.P()
}

// buildModels 收集文件里所有 ormable 消息。
func buildModels(file *protogen.File) ([]*model, error) {
	var models []*model
	for _, msg := range file.Messages {
		m, err := buildModel(msg)
		if err != nil {
			return nil, err
		}
		if m != nil {
			models = append(models, m)
		}
	}
	return models, nil
}

// emitModel 输出一个实体的结构体、TableName、ToPB 与 From。
func emitModel(g *protogen.GeneratedFile, m *model) {
	g.P()
	g.P("// ", m.ormName, " 表 ", m.table, "，对应 proto 消息 ", m.pbName, "。")
	if doc := strings.TrimRight(m.doc, "\n"); doc != "" {
		g.P(doc)
	}
	g.P("type ", m.ormName, " struct {")
	for _, f := range m.fields {
		if c := strings.TrimRight(f.comment, "\n"); c != "" {
			g.P(c)
		}
		line := f.goName + " " + f.ormType.render(g)
		if f.tag != "" {
			line += " `gorm:\"" + f.tag + "\"`"
		}
		g.P(line)
	}
	g.P("}")
	g.P()

	g.P("// TableName 返回 GORM 表名。")
	g.P("func (", m.ormName, ") TableName() string { return ", quote(m.table), " }")

	emitFrom(g, m)
	emitToPB(g, m)
}

// emitFrom 输出 From<Msg>(ctx, *native.Msg) (<Msg>ORM, error)。
func emitFrom(g *protogen.GeneratedFile, m *model) {
	g.P()
	g.P("// From", m.pbName, " 把 proto 消息 ", m.pbName, " 转成 ", m.ormName, "。")
	g.P("func From", m.pbName, "(ctx ", ctxType(g), ", in *", pbType(g, m), ") (", m.ormName, ", error) {")
	g.P("var out ", m.ormName)
	for _, f := range m.fields {
		emitFromField(g, f)
	}
	g.P("return out, nil")
	g.P("}")
}

// emitToPB 输出 (*<Msg>ORM).ToPB(ctx) (*native.Msg, error)。
func emitToPB(g *protogen.GeneratedFile, m *model) {
	g.P()
	g.P("// ToPB 把 ", m.ormName, " 转成 proto 消息 ", m.pbName, "。")
	// 返回指针：protobuf 消息内部带锁，按值返回会触发 copylocks。
	g.P("func (m *", m.ormName, ") ToPB(ctx ", ctxType(g), ") (*", pbType(g, m), ", error) {")
	g.P("var out ", pbType(g, m))
	for _, f := range m.fields {
		emitToPBField(g, f)
	}
	g.P("return &out, nil")
	g.P("}")
}
